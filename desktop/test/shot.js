// Saves screenshots of every screen without showing a window:  electron test/shot.js <url> <key> <outdir> [colors] [mode]
const { app, BrowserWindow } = require('electron');
const path = require('path'), fs = require('fs');
const { ipcMain } = require('electron');
const { theme } = require('../theme');
ipcMain.handle('theme', () => theme()); ipcMain.handle('frame-get', () => false); ipcMain.handle('version', () => '0.3.0'); ipcMain.handle('update-check', () => ({ ok: true, current: '0.3.0', latest: '0.3.0', available: false }));
const [url, key, out, colors = 'clay', mode = 'dark'] = process.argv.slice(-5);
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
app.whenReady().then(async () => {
  const w = new BrowserWindow({ width: +(process.env.W || 1100), height: +(process.env.H || 740), show: false, frame: false, webPreferences: { offscreen: true, preload: path.join(__dirname, '..', 'preload.js') } });
  const log = []; w.webContents.on('console-message', (_e, lvl, msg) => lvl >= 2 && log.push(msg));
  const shot = async (n) => { await wait(350); fs.writeFileSync(path.join(out, n + '.png'), (await w.webContents.capturePage()).toPNG()); };
  const js = (c) => w.webContents.executeJavaScript(c);
  await w.loadFile(path.join(__dirname, '..', 'renderer', 'index.html'));
  await js(`localStorage.clear(); localStorage.setItem('cfg', JSON.stringify({colors:${JSON.stringify(colors)}, mode:${JSON.stringify(mode)}}))`);
  await w.loadFile(path.join(__dirname, '..', 'renderer', 'index.html')); await shot('1-connect');
  await js(`localStorage.setItem('conn', JSON.stringify({url:${JSON.stringify(url)},key:${JSON.stringify(key)}}))`);
  await w.loadFile(path.join(__dirname, '..', 'renderer', 'index.html')); await wait(1500);
  await shot('2-agents');
  await js(`document.querySelector('.item').click()`); await wait(900); await shot('3-chat');
  await js(`document.querySelector('#edit').click()`); await shot('4-editor');
  await js(`document.querySelector('#cancel').click(); document.querySelector('#hrep').click()`); await wait(500); await shot('5-repeat');
  await js(`document.querySelector('[data-t=weekly]').click()`); await wait(300); await shot('6-repeat-weekly');
  await js(`document.querySelector('#jcancel').click(); document.querySelector('[data-tab=activity]').click()`); await wait(900); await shot('9-activity');
  await js(`document.querySelector('[data-tab=usage]').click()`); await shot('10-usage');
  await js(`document.querySelector('[data-tab=settings]').click()`); await wait(900); await shot('11-settings');
  await js(`document.querySelector('.page').scrollTop = 560`); await wait(300); await shot('12-settings2');
  console.log('console errors:', JSON.stringify(log));
  app.quit();
});
